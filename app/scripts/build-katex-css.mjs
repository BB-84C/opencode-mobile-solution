// Writes src/components/opencode/katex-inline-css.generated.ts: KaTeX's
// stylesheet with its woff2 fonts inlined as data URLs.
//
// The phone renders math-bearing messages in a WebView loaded from an HTML
// string, and such a page has no reliable way to read font files from the app
// bundle. Without the fonts KaTeX falls back to system glyphs and formulas
// misalign. Re-run after upgrading katex: npm run build:katex-css
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const appRoot = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const katexRoot = path.join(appRoot, "node_modules", "katex");
const { version } = JSON.parse(fs.readFileSync(path.join(katexRoot, "package.json"), "utf8"));
const css = fs.readFileSync(path.join(katexRoot, "dist", "katex.min.css"), "utf8");

let inlined = 0;
const out = css.replace(/src:url\(fonts\/([^)]+)\.woff2\) format\("woff2"\)(,url\([^)]+\) format\("[^"]+"\))*/g, (_match, name) => {
  const font = fs.readFileSync(path.join(katexRoot, "dist", "fonts", `${name}.woff2`));
  inlined += 1;
  return `src:url(data:font/woff2;base64,${font.toString("base64")}) format("woff2")`;
});
if (inlined === 0 || /url\(fonts\//.test(out)) {
  process.stderr.write("build-katex-css: the stylesheet's font declarations changed shape; update the pattern\n");
  process.exit(1);
}

const target = path.join(appRoot, "src", "components", "opencode", "katex-inline-css.generated.ts");
fs.writeFileSync(
  target,
  `// Generated by scripts/build-katex-css.mjs from katex ${version}. Do not edit.\n` +
    `export const KATEX_VERSION = ${JSON.stringify(version)};\n` +
    `export const KATEX_CSS = ${JSON.stringify(out)};\n`,
);
process.stdout.write(`build-katex-css: ${inlined} fonts inlined, ${(fs.statSync(target).size / 1024).toFixed(0)} KB -> ${path.relative(appRoot, target)}\n`);
